 '        CREATE TABLE IF NOT EXISTS daemon_run_checkpoints (\n'
 '            id TEXT PRIMARY KEY,\n'
 '            run_id TEXT NOT NULL REFERENCES daemon_runs(id) ON DELETE CASCADE,\n'
 '            sequence INTEGER NOT NULL,\n'
 '            safe_to_resume INTEGER NOT NULL,\n'
 '            executor_state TEXT NOT NULL,\n'
 '            created_at TEXT NOT NULL,\n'
 '            UNIQUE (run_id, sequence)\n'
 '        );\n'
 '        CREATE INDEX IF NOT EXISTS daemon_checkpoints_run\n'
