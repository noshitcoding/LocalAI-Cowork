 '            ON daemon_runs(thread_id, created_at);\n'
 '\n'
 '        CREATE TABLE IF NOT EXISTS daemon_run_events (\n'
 '            run_id TEXT NOT NULL REFERENCES daemon_runs(id) ON DELETE CASCADE,\n'
 '            sequence INTEGER NOT NULL,\n'
 '            event_json TEXT NOT NULL,\n'
 '            PRIMARY KEY (run_id, sequence)\n'
 '        );\n'
 '\n'
 '        CREATE TABLE IF NOT EXISTS daemon_project_bindings (\n'
 '            project_id TEXT PRIMARY KEY,\n'
 '            workspace_path TEXT NOT NULL,\n'
 '            updated_at TEXT NOT NULL\n'
 '        );\n'
 '\n'
 '        CREATE TABLE IF NOT EXISTS daemon_provider_bindings (\n'
 '            profile_id TEXT PRIMARY KEY,\n'
 '            encrypted_binding TEXT NOT NULL,\n'
 '            updated_at TEXT NOT NULL\n'
 '        );\n'
 '\n'
 '        CREATE TABLE IF NOT EXISTS daemon_mcp_bindings (\n'
 '            server_id TEXT PRIMARY KEY,\n'
 '            encrypted_binding TEXT NOT NULL,\n'
 '            updated_at TEXT NOT NULL\n'
 '        );\n'
 '\n'
 '        CREATE TABLE IF NOT EXISTS daemon_run_model_configs (\n'
 '            run_id TEXT PRIMARY KEY REFERENCES daemon_runs(id) ON DELETE CASCADE,\n'
 '            encrypted_config TEXT NOT NULL,\n'
 '            created_at TEXT NOT NULL\n'
 '        );\n'
 '\n'
 '        CREATE TABLE IF NOT EXISTS daemon_run_workspaces (\n'
 '            run_id TEXT PRIMARY KEY REFERENCES daemon_runs(id) ON DELETE CASCADE,\n'
