DAEMON_SYNC = ('\n'
 '        CREATE TABLE IF NOT EXISTS daemon_sync_peers (\n'
 '            peer_id TEXT PRIMARY KEY,\n'
 '            local_cursor INTEGER NOT NULL DEFAULT 0 CHECK (local_cursor >= 0),\n'
 '            remote_cursor INTEGER NOT NULL DEFAULT 0 CHECK (remote_cursor >= 0),\n'
 '            updated_at TEXT NOT NULL\n'
 '        );\n'
 '        CREATE TABLE IF NOT EXISTS daemon_sync_conflicts (\n'
 '            id TEXT PRIMARY KEY,\n'
 '            peer_id TEXT NOT NULL REFERENCES daemon_sync_peers(peer_id) ON DELETE CASCADE,\n'
 '            entity_type TEXT NOT NULL,\n'
 '            entity_id TEXT NOT NULL,\n'
 '            local_entity_json TEXT,\n'
 '            remote_entity_json TEXT NOT NULL,\n'
 '            created_at TEXT NOT NULL,\n'
 '            resolved_at TEXT,\n'
 "            resolution TEXT CHECK (resolution IS NULL OR resolution IN ('use_remote', "
 "'keep_local'))\n"
 '        );\n'
 '        CREATE UNIQUE INDEX IF NOT EXISTS daemon_sync_conflicts_open\n'
 '            ON daemon_sync_conflicts(peer_id, entity_type, entity_id)\n'
 '            WHERE resolved_at IS NULL;\n'
 '        ')

