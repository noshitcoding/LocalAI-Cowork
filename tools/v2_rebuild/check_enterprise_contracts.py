"""Read-only check of the Enterprise pin against the current common V2 closure.

Unrelated V2 source/generator additions may change provenance without changing
these execution types. Report both facts; never upgrade either to runtime proof.
"""
import argparse
import json
from pathlib import Path
import re

from export_enterprise_contracts import FILES, build, sha


def check(enterprise: Path) -> dict:
    enterprise=enterprise.resolve(strict=True)
    pin=enterprise/'server/cowork-server/src/v2_runtime_contract_pin.rs'
    if pin.is_symlink() or not pin.resolve(strict=True).is_relative_to(enterprise) or not pin.is_file() or pin.stat().st_size>16*1024:
        raise ValueError('Invalid Enterprise pin source')
    text=pin.read_text(encoding='utf-8')
    match=re.search(r'pub\(super\) const BUNDLE_ID: &str = "([a-f0-9]{64})";',text)
    if not match or not text.startswith('// Generated by V2 tools/v2_rebuild/export_enterprise_contracts.py;'):
        raise ValueError('Not a generated Enterprise pin')
    bundle_id=match[1]
    parent=(enterprise/'contracts/v2-runtime').resolve(strict=True)
    root=parent/bundle_id
    if not parent.is_relative_to(enterprise) or root.is_symlink() or root.resolve(strict=True).parent!=parent:
        raise ValueError('Pinned bundle is outside the Enterprise artifact directory')
    if {path.name for path in root.iterdir()}!={*FILES,'manifest.json'}:
        raise ValueError('Unexpected artifact layout')
    content={}
    for name in (*FILES,'manifest.json'):
        path=root/name
        if path.is_symlink() or not path.is_file() or path.stat().st_size>2*1024*1024:
            raise ValueError('Invalid pinned artifact file')
        content[name]=path.read_bytes()
    if sha(content['manifest.json'])!=bundle_id:
        raise ValueError('Manifest no longer matches the Enterprise pin')
    manifest=json.loads(content['manifest.json'])
    if manifest.get('format_version')!=1 or manifest.get('kind')!='localai-cowork-v2-execution-contracts' or set(manifest.get('files',{}))!=set(FILES):
        raise ValueError('Unsupported pinned manifest')
    if manifest.get('qualification')!='source_contract_only; no actor, snapshot, installed-runtime or execution attestation':
        raise ValueError('Unsupported artifact qualification')
    for name in FILES:
        if manifest['files'][name]!={'sha256':sha(content[name]),'bytes':len(content[name])}:
            raise ValueError('Pinned contract file changed')
    current_id,current,_=build()
    same=all(content[name]==current[name] for name in FILES)
    if not same:
        raise ValueError('The common execution schema changed; coordinate and pin a new version before consuming it')
    return {'passed':True,'bundle_id':bundle_id,'producer_version':manifest['producer_version'],
            'definition_count':manifest['definition_count'],'common_execution_contracts_match_current':True,
            'same_producer_snapshot':current_id==bundle_id,'execution_qualified':False}


if __name__=='__main__':
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--enterprise-root',required=True,type=Path)
    parser.add_argument('--output',type=Path)
    args=parser.parse_args();result=check(args.enterprise_root)
    if args.output:args.output.write_text(json.dumps(result,indent=2)+'\n',encoding='utf-8')
    print(json.dumps(result))
